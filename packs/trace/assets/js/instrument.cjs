// 실행 흐름 계측기 (JS · TS · JSX · TSX): 원본 소스에 기록 호출을 끼워 넣는다. kedovi trace 의 Vite 플러그인 · Jest 변환기 · Node 로더가 쓴다
/*
 * instrument(code, file, { ts, src }) → { code, fns } | null
 *   ts  : typescript 모듈 (파서로만 쓴다. 프로젝트에 있는 것, 없으면 킷이 받아 둔 것)
 *   src : 기록에 남길 파일 경로 (프로젝트 기준 상대)
 *   mapLine(줄) → 원본 줄 (선택: tsc 로 빌드한 dist JS 를 계측할 때 소스맵으로)
 * 원칙
 *   - 줄바꿈을 넣지 않고 원래 줄 번호를 숫자로 박는다 → 뒤에 TS 변환 · 번들이 와도 줄이 원본과 맞는다 (소스맵 불필요)
 *   - 함수 본문: 시작 = 호출 기록(인자), 문장마다 = 그 줄 직전 지역 변수, return = 반환값, catch = 잡은 곳, 끝 = 반환 · 예외
 *   - 지역 변수는 그 줄에서 이미 선언된 것만 (TDZ 오류가 나지 않게). 함수 밖(모듈 최상위)은 기록하지 않는다
 *   - await 앞뒤로 「지금 호출」 을 되돌려 비동기 호출 나무가 섞이지 않게 한다
 *   - 게터 · 세터 · 상속 클래스 생성자는 건너뛴다 (super 앞 코드 제약)
 * 기록 객체는 globalThis.__kedoviT (runtime.js). 없으면 아무 일도 안 하는 대역을 쓴다 (계측된 파일이 기록 없이도 돈다)
 */
'use strict';

const RT = '__ak';
const NOOP = `const ${RT}=globalThis.__kedoviT||{d(){return 0},e(){return 0},l(){},r(k,v){return v},x(){},f(){},c(){},s(k,v){return v},w(k,v){return v}};`;
const ROUTE = /^(get|post|put|patch|delete|del|all|head|options)$/i;

/** 도구가 만든 코드(OpenAPI 클라이언트 · GraphQL 코드 생성 등)인가: 기록하면 잡음만 많다 */
function generated(code, file) {
  if (/(^|[\\/])(generated|__generated__|gen)[\\/]|\.gen(erated)?\.[cm]?[jt]sx?$/.test(file)) return true;
  return /@generated|auto-?generated|do not (edit|modify)|generated by/i.test(code.slice(0, 600));
}

function instrument(code, file, opts) {
  const ts = opts.ts;
  if (!opts.keepGenerated && generated(code, file)) return null;
  const kind = /\.tsx$/.test(file) ? ts.ScriptKind.TSX : /\.ts$|\.mts$|\.cts$/.test(file) ? ts.ScriptKind.TS : /\.jsx$/.test(file) ? ts.ScriptKind.JSX : ts.ScriptKind.JS;
  const sf = ts.createSourceFile(file, code, ts.ScriptTarget.Latest, true, kind);
  if (sf.parseDiagnostics && sf.parseDiagnostics.length) return null; // 못 읽는 문법이면 손대지 않는다
  const edits = []; // { pos, text, ord } ord: 같은 자리에서 여는 것은 바깥 먼저, 닫는 것은 안쪽 먼저
  const fns = []; // [이름, 소속, 선언 줄, 1 = 진입점(라우트) · 2 = 미들웨어]
  const classes = new Set(); // 이 파일에서 선언한 클래스 (런타임이 값을 속까지 읽는 기준)
  const lineOf = (pos) => { const p = sf.getLineAndCharacterOfPosition(pos); return opts.mapLine ? opts.mapLine(p.line + 1, p.character) : p.line + 1; }; // 빌드된 JS 면 소스맵으로 원본 줄
  const base = (file.split(/[\\/]/).pop() || '').replace(/\.[^.]+$/, '');
  let depth = 0;
  const open = (pos, text) => edits.push({ pos, text, ord: depth });
  const close = (pos, text) => edits.push({ pos, text, ord: 1e6 - depth });

  /** 바인딩 이름 (구조 분해 포함) */
  function names(b, out = []) {
    if (!b) return out;
    if (ts.isIdentifier(b)) out.push(b.text);
    else if (ts.isObjectBindingPattern(b) || ts.isArrayBindingPattern(b)) for (const e of b.elements) if (!ts.isOmittedExpression(e)) names(e.name, out);
    return out;
  }
  const obj = (list, withThis) => `{${[...(withThis ? ['this:this'] : []), ...[...new Set(list)].filter((n) => n !== 'this' && n !== RT && n !== '__k')].join(',')}}`;

  /** 이름 없는 함수의 이름 짓기: 변수 · 속성 · 호출 인자 · JSX 속성 */
  function nameOf(fn) {
    if (ts.isConstructorDeclaration(fn)) return { name: 'constructor' };
    if (fn.name && ts.isIdentifier(fn.name)) return { name: fn.name.text };
    if (fn.name && (ts.isStringLiteral(fn.name) || ts.isPrivateIdentifier(fn.name))) return { name: fn.name.text };
    const p = fn.parent;
    if (!p) return { name: '(익명)' };
    if (ts.isVariableDeclaration(p) && ts.isIdentifier(p.name)) return { name: p.name.text };
    if ((ts.isPropertyAssignment(p) || ts.isPropertyDeclaration(p)) && p.name && (ts.isIdentifier(p.name) || ts.isStringLiteral(p.name))) return { name: p.name.text };
    if (ts.isExportAssignment(p)) return { name: 'default' };
    if (ts.isJsxExpression(p) && p.parent && ts.isJsxAttribute(p.parent)) {
      const el = p.parent.parent && p.parent.parent.parent; // JsxAttributes → 요소
      const tag = el && el.tagName ? el.tagName.getText(sf) : '';
      return { name: `${tag ? `${tag} ` : ''}${p.parent.name.getText(sf)}` };
    }
    if (ts.isNewExpression(p)) return { name: `new ${p.expression.getText(sf).slice(0, 40)}` };
    if (ts.isCallExpression(p)) {
      const callee = p.expression;
      const prop = ts.isPropertyAccessExpression(callee) ? callee.name.text : ts.isIdentifier(callee) ? callee.text : '';
      const first = p.arguments[0];
      if (prop === 'use' && /^(app|router|server|api)$/i.test(ts.isPropertyAccessExpression(callee) ? callee.expression.getText(sf) : '')) return { name: '미들웨어', mw: true };
      if (ROUTE.test(prop) && first && (ts.isStringLiteral(first) || ts.isNoSubstitutionTemplateLiteral(first)) && p.arguments.indexOf(fn) > 0) {
        return { name: `${prop.toUpperCase().replace('DEL', 'DELETE').replace('DELETEETE', 'DELETE')} ${first.text}`, ent: true };
      }
      // useCallback(() => …) · useMemo 는 변수 이름을 쓴다
      if (/^use(Callback|Memo)$/.test(prop) && p.parent && ts.isVariableDeclaration(p.parent) && ts.isIdentifier(p.parent.name)) return { name: p.parent.name.text };
      // 그 밖의 인자 함수: 부른 대상 (products.map · fetchProducts().then · setTimeout)
      const callee2 = callee.getText(sf).replace(/\s+/g, '');
      if (prop) return { name: callee2.length <= 32 ? callee2 : prop };
    }
    return { name: '(익명)' };
  }

  /** 소속: 클래스 이름 · 감싼 함수(컴포넌트) 이름 · 파일 이름 */
  function ownerOf(fn) {
    for (let p = fn.parent; p; p = p.parent) {
      if ((ts.isClassDeclaration(p) || ts.isClassExpression(p)) && p.name) return p.name.text;
      if (ts.isFunctionDeclaration(p) && p.name) return p.name.text;
      if ((ts.isArrowFunction(p) || ts.isFunctionExpression(p)) && p.parent && ts.isVariableDeclaration(p.parent) && ts.isIdentifier(p.parent.name)) return p.parent.name.text;
    }
    return base;
  }

  const isFn = (n) => ts.isFunctionDeclaration(n) || ts.isFunctionExpression(n) || ts.isArrowFunction(n) || ts.isMethodDeclaration(n) || ts.isConstructorDeclaration(n);

  function skipFn(fn) {
    if (!fn.body) return true; // 선언만 (overload · abstract · declare)
    if (ts.isConstructorDeclaration(fn)) {
      const cls = fn.parent;
      if (cls && cls.heritageClauses && cls.heritageClauses.some((h) => h.token === ts.SyntaxKind.ExtendsKeyword)) return true;
    }
    if (fn.asteriskToken) return true; // 제너레이터: yield 사이 호출 나무가 꼬인다
    return false;
  }

  /** 함수 하나 계측. scope = 이미 선언된 지역 이름 */
  function doFn(fn) {
    if (skipFn(fn)) { ts.forEachChild(fn, visit); return; }
    const id = fns.length;
    const { name, ent, mw } = nameOf(fn);
    const params = [];
    for (const p of fn.parameters) if (!(ts.isIdentifier(p.name) && p.name.text === 'this')) names(p.name, params);
    const withThis = ts.isMethodDeclaration(fn) || ts.isConstructorDeclaration(fn) || ts.isFunctionExpression(fn) && ts.isPropertyAssignment(fn.parent);
    fns.push([name, ownerOf(fn), lineOf(fn.getStart(sf)), ent ? 1 : mw ? 2 : 0]);
    const head = `const __k=${RT}.e(__f,${id},${obj(params, withThis)});try{`;
    const tail = `}catch(__x){${RT}.x(__k,__x);throw __x}finally{${RT}.f(__k)}`;
    depth += 1;
    const body = fn.body;
    const outer = fnCtx;
    fnCtx = { async: !!(fn.modifiers && fn.modifiers.some((m) => m.kind === ts.SyntaxKind.AsyncKeyword)), line: 0 };
    if (ts.isBlock(body)) {
      let at = body.getStart(sf) + 1;
      let i = 0;
      while (i < body.statements.length && ts.isExpressionStatement(body.statements[i]) && ts.isStringLiteral(body.statements[i].expression)) { at = body.statements[i].end; i += 1; } // "use strict" 같은 지시문 뒤
      open(at, head);
      block(body.statements.slice(i), params);
      close(body.end - 1, tail);
    } else {
      // 화살표 함수의 식 본문: (x) => expr → { …; return expr }
      const L = lineOf(body.getStart(sf));
      open(body.getStart(sf), `{${head}${RT}.l(__k,${L},${obj(params)});return ${RT}.r(__k,(`);
      expr(body);
      close(body.end, `))${tail}}`);
    }
    fnCtx = outer;
    depth -= 1;
  }
  let fnCtx = null;

  /** 문장 목록: 문장마다 앞에 줄 기록. 선언은 다음 문장부터 보인다 */
  function block(stmts, scope) {
    const seen = [...scope];
    for (const s of stmts) {
      stmt(s, seen);
      if (ts.isVariableStatement(s)) for (const d of s.declarationList.declarations) names(d.name, seen);
      else if ((ts.isFunctionDeclaration(s) || ts.isClassDeclaration(s)) && s.name) seen.push(s.name.text);
    }
  }

  function probe(s, scope) {
    const L = lineOf(s.getStart(sf));
    if (fnCtx && fnCtx.line === L) return; // 한 줄에 문장이 여럿 (if (a) continue; 등): 첫 문장에서 한 번만
    if (fnCtx) fnCtx.line = L;
    open(s.getStart(sf), `${RT}.l(__k,${L},${obj(scope)});`);
  }

  /** 문장이 블록이 아니면 { } 로 감싸 기록을 넣는다 (if (a) x; → if (a) {기록 x;}) */
  function body(s, scope) {
    if (!s) return;
    if (ts.isBlock(s)) { depth += 1; block(s.statements, scope); depth -= 1; return; }
    depth += 1;
    open(s.getStart(sf), '{');
    stmt(s, scope);
    close(s.end, '}');
    depth -= 1;
  }

  function stmt(s, scope) {
    if (ts.isEmptyStatement(s) || ts.isInterfaceDeclaration(s) || ts.isTypeAliasDeclaration(s) || ts.isModuleDeclaration(s)) return;
    probe(s, scope);
    if (ts.isIfStatement(s)) { expr(s.expression); body(s.thenStatement, scope); if (s.elseStatement) body(s.elseStatement, scope); return; }
    if (ts.isForStatement(s)) {
      const inner = [...scope];
      if (s.initializer) { expr(s.initializer); if (ts.isVariableDeclarationList(s.initializer)) for (const d of s.initializer.declarations) names(d.name, inner); }
      if (s.condition) expr(s.condition);
      if (s.incrementor) expr(s.incrementor);
      body(s.statement, inner);
      return;
    }
    if (ts.isForOfStatement(s) || ts.isForInStatement(s)) {
      const inner = [...scope];
      if (ts.isVariableDeclarationList(s.initializer)) for (const d of s.initializer.declarations) names(d.name, inner);
      expr(s.expression);
      body(s.statement, inner);
      return;
    }
    if (ts.isWhileStatement(s) || ts.isDoStatement(s)) { expr(s.expression); body(s.statement, scope); return; }
    if (ts.isLabeledStatement(s)) { body(s.statement, scope); return; }
    if (ts.isBlock(s)) { depth += 1; block(s.statements, scope); depth -= 1; return; }
    if (ts.isTryStatement(s)) {
      depth += 1; block(s.tryBlock.statements, scope); depth -= 1;
      if (s.catchClause) {
        const inner = [...scope];
        const v = s.catchClause.variableDeclaration;
        if (v) names(v.name, inner);
        const b = s.catchClause.block;
        if (v && ts.isIdentifier(v.name)) open(b.getStart(sf) + 1, `${RT}.c(__k,${v.name.text},${lineOf(s.catchClause.getStart(sf))});`);
        depth += 1; block(b.statements, inner); depth -= 1;
      }
      if (s.finallyBlock) { depth += 1; block(s.finallyBlock.statements, scope); depth -= 1; }
      return;
    }
    if (ts.isSwitchStatement(s)) {
      expr(s.expression);
      // case 마다 따로 (앞 case 의 let · const 는 건너뛰어 들어오면 TDZ)
      for (const c of s.caseBlock.clauses) { if (ts.isCaseClause(c)) expr(c.expression); depth += 1; block(c.statements, scope); depth -= 1; }
      return;
    }
    if (ts.isReturnStatement(s)) {
      if (s.expression) { open(s.expression.getStart(sf), `${RT}.r(__k,(`); expr(s.expression); close(s.expression.end, '))'); }
      return;
    }
    if (ts.isFunctionDeclaration(s) || ts.isClassDeclaration(s)) { visit(s); return; }
    expr(s);
  }

  /** 식 안: 함수가 나오면 계측, await 는 「지금 호출」 되돌리기 */
  function expr(n) {
    if (!n) return;
    if (isFn(n)) { doFn(n); return; }
    if (ts.isClassDeclaration(n) || ts.isClassExpression(n)) { visit(n); return; }
    if (ts.isAwaitExpression(n) && fnCtx && fnCtx.async) {
      depth += 1;
      open(n.getStart(sf), `${RT}.w(__k,`);
      open(n.expression.getStart(sf), `${RT}.s(__k,`);
      expr(n.expression);
      close(n.expression.end, ')');
      close(n.end, ')');
      depth -= 1;
      return;
    }
    ts.forEachChild(n, expr);
  }

  /** 함수 밖 (모듈 최상위 · 클래스 몸통) */
  function visit(n) {
    if (isFn(n)) { const outer = fnCtx; fnCtx = null; doFn(n); fnCtx = outer; return; }
    if (ts.isGetAccessor(n) || ts.isSetAccessor(n)) return;
    if (ts.isClassDeclaration(n) || ts.isClassExpression(n)) { if (n.name) classes.add(n.name.text); const outer = fnCtx; fnCtx = null; ts.forEachChild(n, visit); fnCtx = outer; return; }
    ts.forEachChild(n, visit);
  }

  const outerFn = fnCtx;
  ts.forEachChild(sf, visit);
  fnCtx = outerFn;
  if (!fns.length && !classes.size) return null;

  // 맨 위 (지시문 "use client" 등 뒤): 기록 객체 · 이 파일 함수 목록
  let top = 0;
  for (const s of sf.statements) { if (ts.isExpressionStatement(s) && ts.isStringLiteral(s.expression)) top = s.end; else break; }
  edits.push({ pos: top, text: `${NOOP}const __f=${RT}.d(${JSON.stringify(opts.src || file)},${JSON.stringify(fns)},${JSON.stringify([...classes])});`, ord: -1 });

  edits.sort((a, b) => a.pos - b.pos || a.ord - b.ord);
  let out = '';
  // TS 파일: 끼운 코드의 타입 오류로 타입 검사기(ts-jest 등)가 실패하지 않게. 한 줄이 밀리지만 기록 줄 번호는 숫자로 박혀 있다
  if (/\.[cm]?tsx?$/.test(file) && !/^\s*\/\/\s*@ts-nocheck/.test(code)) {
    if (code.startsWith('#!')) { const nl = code.indexOf('\n') + 1; edits.unshift({ pos: nl, text: '// @ts-nocheck\n', ord: -2 }); } else edits.unshift({ pos: 0, text: '// @ts-nocheck\n', ord: -2 });
    edits.sort((a, b) => a.pos - b.pos || a.ord - b.ord);
  }
  let last = 0;
  const word = /[\w$]/;
  for (const e of edits) {
    out += code.slice(last, e.pos);
    // 압축된 코드(return{…} · await(x))에서 끼운 이름이 앞 낱말에 붙지 않게
    out += word.test(out[out.length - 1] || '') && word.test(e.text[0]) ? ` ${e.text}` : e.text;
    last = e.pos;
  }
  out += code.slice(last);
  return { code: out, fns };
}

module.exports = { instrument, generated };
